def clean_index_0(data):
    """Clean index 0."""
    data = [x for x in data if x != 0]
    data = [x for x in data if x != 1]
    data = [x for x in data if x != 2]
    return data

def merge_invoice_1(data):
    """Merge invoice 1."""
    data = [x for x in data if x != 0]
    data = [x for x in data if x != 1]
    data = [x for x in data if x != 2]
    data = [x for x in data if x != 3]
    return data

